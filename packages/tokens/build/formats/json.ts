import { MODE_KIND_NAMES, MODE_KINDS, modesOf, PREFIX } from '../config.ts';
import type { TokenModel } from '../model.ts';
import { pathOf, tierOfToken, valueOf } from '../passes.ts';

/**
 * Resolved values for the docs site (Step 9) and design-tool sync: every
 * token in every tier, with its source value, alias, and per-mode values.
 */
export function renderJson(model: TokenModel): string {
  const tokens: Record<string, unknown> = {};
  for (const token of model.all) {
    const path = pathOf(token);
    const tier = tierOfToken(token);
    const source: unknown = token.original.$value;
    const deprecated: unknown = token.$deprecated;
    const alias = typeof source === 'string' ? /^\{([^{}]+)\}$/.exec(source)?.[1] : undefined;

    const modes: Record<string, Record<string, string | number>> = {};
    for (const kind of MODE_KIND_NAMES) {
      const { paths, passes } = model.kinds[kind];
      if (!paths.includes(path)) continue;
      modes[kind] = Object.fromEntries(
        modesOf(kind).map((mode) => {
          const modeToken = passes.get(mode)?.byPath.get(path);
          if (!modeToken) throw new Error(`${path} is missing from ${kind} mode ${mode}`);
          return [mode, valueOf(modeToken)];
        }),
      );
    }

    tokens[path] = {
      tier,
      type: token.$type,
      description: token.$description,
      value: valueOf(token),
      ...(alias === undefined ? { source } : { aliasOf: alias }),
      ...(tier === 'reference' ? {} : { cssVariable: `--${token.name}` }),
      ...(Object.keys(modes).length > 0 ? { modes } : {}),
      ...(deprecated === undefined ? {} : { deprecated }),
    };
  }

  const document = {
    $comment:
      'Generated by @mission-ui/tokens from the DTCG files in packages/tokens/tokens. Do not edit.',
    cssPrefix: `--${PREFIX}-`,
    modes: Object.fromEntries(
      MODE_KIND_NAMES.map((kind) => [
        kind,
        { default: MODE_KINDS[kind].defaultMode, values: modesOf(kind) },
      ]),
    ),
    tokens,
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}
